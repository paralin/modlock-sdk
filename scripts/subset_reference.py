def main() -> None:
    """Expand repeated binary trees into an inventory consumed by depot_match."""
    targets = []
    for line in FILES.strip().splitlines():
        name, size, sha1, sha256 = line.split()
        trees = ("bin_cs2",) if name in ("foreign.signatures", "system.signatures") else (
            "bin", "bin_cs2", "bin_server", "bin_tools"
        )
        for tree in trees:
            targets.append({"path": f"game/{tree}/win64/{name}", "bytes": int(size),
                            "sha1": sha1, "sha256": sha256})
    output = Path("inventories/verified-subset.json")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(targets, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(targets)} reference paths to {output}")


if __name__ == "__main__":
    main()
